// 离线生成器；不编入 Android 应用。算法参考 CUIDemo/font.c。
#define STB_TRUETYPE_IMPLEMENTATION
#include "vendor/stb_truetype.h"
#include <stdio.h>
#include <stdbool.h>
#include <stdlib.h>
#include <string.h>
#define ATLAS_SIZE 4096

int main(int argc, char **argv) {
    if (argc != 5) { fprintf(stderr, "usage: font-atlas font.ttf codepoints header atlas\n"); return 1; }
    FILE *font = fopen(argv[1], "rb");
    if (!font) return 1;
    fseek(font, 0, SEEK_END); long length = ftell(font); rewind(font);
    unsigned char *data = malloc((size_t)length);
    if (!data || fread(data, 1, (size_t)length, font) != (size_t)length) return 1;
    fclose(font);
    stbtt_fontinfo info;
    if (!stbtt_InitFont(&info, data, stbtt_GetFontOffsetForIndex(data, 0))) return 1;
    if (info.cff.size) { fprintf(stderr, "SDF requires TrueType outlines, not CFF cubic curves\n"); return 1; }
    FILE *cps = fopen(argv[2], "r"), *header = fopen(argv[3], "w"), *raw = fopen(argv[4], "wb");
    if (!cps || !header || !raw) return 1;
    unsigned char *atlas = calloc(ATLAS_SIZE * ATLAS_SIZE, 1);
    if (!atlas) return 1;
    const float scale = stbtt_ScaleForMappingEmToPixels(&info, 40);
    fprintf(header, "// Generated by scripts/generate-font.sh; Noto Sans CJK SC, SIL OFL 1.1.\n");
    fprintf(header, "static const Glyph GLYPHS[] = {\n");
    unsigned cp; int x = 1, y = 1, row_h = 0, count = 0;
    while (fscanf(cps, "%u", &cp) == 1) {
        if (!stbtt_FindGlyphIndex(&info, (int)cp)) { fprintf(stderr, "missing U+%04X\n", cp); return 1; }
        int advance, bearing, w = 0, h = 0, xo = 0, yo = 0;
        stbtt_GetCodepointHMetrics(&info, (int)cp, &advance, &bearing);
        unsigned char *sdf = stbtt_GetCodepointSDF(&info, scale, (int)cp, 5, 128, 24, &w, &h, &xo, &yo);
        if (x + w + 1 >= ATLAS_SIZE) { x = 1; y += row_h + 1; row_h = 0; }
        if (y + h + 1 >= ATLAS_SIZE) { fprintf(stderr, "atlas overflow\n"); return 1; }
        if (sdf) for (int r = 0; r < h; ++r) memcpy(atlas + (y+r)*ATLAS_SIZE+x, sdf+r*w, (size_t)w);
        fprintf(header, "{%u,%d,%d,%d,%d,%d,%d,%.4ff},%s", cp, x, y, w, h, xo, yo, advance*scale, count%16==15?"\n":"");
        stbtt_FreeSDF(sdf, NULL);
        x += w + 1; if (h > row_h) row_h = h; ++count;
    }
    fprintf(header, "\n};\n");
    bool ok = fwrite(atlas, 1, ATLAS_SIZE*ATLAS_SIZE, raw) == ATLAS_SIZE*ATLAS_SIZE;
    fclose(cps); fclose(header); fclose(raw); free(atlas); free(data);
    fprintf(stderr, "%d glyphs, atlas height %d/%d\n", count, y+row_h, ATLAS_SIZE);
    return ok ? 0 : 1;
}
